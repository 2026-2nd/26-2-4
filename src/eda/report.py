def _fmt(v, nd=1):
    if isinstance(v, str):
        return v
    if pd.isna(v):
        return ''
    if float(v).is_integer() and abs(v) >= 1000:
        return f'{int(v):,}'
    if float(v).is_integer():
        return f'{int(v)}'
    return f'{v:,.{nd}f}'


def md(t, cols=None, nd=1, rename=None):
    """DataFrame → 마크다운 표."""
    t = t if cols is None else t[cols]
    t = t.copy()
    for c in t.columns:   # 연도는 천 단위 쉼표 없이
        if '연도' in str(c) or '년도' in str(c):
            t[c] = t[c].map(lambda v: '' if pd.isna(v) else str(int(v)))
    t = t.rename(columns=rename or {})
    num = [pd.api.types.is_numeric_dtype(t[c]) for c in t.columns]
    out = ['| ' + ' | '.join(map(str, t.columns)) + ' |', '|' + '|'.join('---:' if n else '---' for n in num) + '|']
    for row in t.itertuples(index=False):
        out.append('| ' + ' | '.join(_fmt(v, nd) for v in row) + ' |')
    return '\n'.join(out)


